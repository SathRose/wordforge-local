(function () {
  const api=window.__WFAPI, db=api.getDB(), results=[];
  const check=(name,pass)=>{if(!pass)throw new Error(name);results.push(name);};
  check('Bundled HTTPS local app loads with no PC server',location.href==='https://appassets.androidplatform.net/assets/index.html');
  check('24 built-in books and 24027 entries',api.books().length===24&&api.words().length===24027);
  check('12 custom books / 410 source entries',Object.keys(db.custom).length===12&&Object.values(db.custom).reduce((s,b)=>s+b.words.length,0)===410);
  check('Native export and TTS interfaces present',typeof WordForgeNative.exportText==='function'&&typeof WordForgeNative.ttsSpeak==='function');
  check('No voice means listening questions unavailable',WordForgeNative.ttsAvailable()||!api.ttsReady());
  api.go('study');
  const switchButton=[...document.querySelectorAll('button')].find(b=>b.textContent==='换词书');
  check('Study page switch-book button exists',!!switchButton);switchButton.click();
  check('Custom books occupy the first 12 slots',[...document.querySelectorAll('#modal [data-book]')].slice(0,12).every(b=>b.dataset.book.startsWith('@')));
  const before=JSON.stringify(db);
  document.getElementById('bookSortEdit').click();
  document.querySelector('[data-sort-id="cet4"][data-sort-action="top"]').click();
  document.getElementById('bookSortCancel').click();
  check('Cancel leaves all DB fields unchanged',JSON.stringify(db)===before);
  document.getElementById('bookSortEdit').click();
  document.querySelector('[data-sort-id="cet4"][data-sort-action="top"]').click();
  document.getElementById('bookSortSave').click();
  check('Sorting persists to Android WebView local storage',JSON.parse(localStorage.getItem('wordforge_v1')).bookPickerOrder[0]==='cet4');
  document.getElementById('bookSortEdit').click();
  document.getElementById('bookSortReset').click();
  document.getElementById('bookSortSave').click();
  check('Reset custom-first order works',document.querySelector('#modal [data-book]').dataset.book==='@nhce4_u1_part1_p007_009');
  document.querySelector('[data-book="@vocabgo_cet4_2_list_01"]').click();
  const source = db.custom.vocabgo_cet4_2_list_01.words.map(w=>w[api.F.W]);
  const unseen = api.buildQueue('all').filter(w=>!db.prog[w]);
  check('Source order remains accent/clash/core and new-word queue respects it',source.slice(0,3).join(',')==='accent,clash,core'&&unseen.every((w,i)=>i===0||source.indexOf(w)>source.indexOf(unseen[i-1])));
  api.go('study');api.showBookOrderEditor();
  const body=document.querySelector('#modal .modal-b'),footer=document.querySelector('#modal .modal-f');
  check('Native mobile modal has no horizontal overflow',body.scrollWidth<=body.clientWidth&&footer.scrollWidth<=footer.clientWidth);
  document.getElementById('bookSortCancel').click();document.getElementById('mClose2').click();
  api.getDB().cfg.modes=['card'];api.getDB().cfg.autoSpeak=false;
  api.startSession('learn');
  const word=api.session().queue[api.session().i];
  api.grade(word,3);
  window.__wfFlushSave();
  check('Review progress writes to persistent storage',!!JSON.parse(localStorage.getItem('wordforge_v1')).prog[word]);
  api.go('study');api.showBookPicker();
  return {passed:results.length,checks:results,voiceReady:WordForgeNative.ttsAvailable(),firstWord:word,progress:api.getDB().prog[word],screen:{width:innerWidth,height:innerHeight},customCount:Object.keys(api.getDB().custom).length};
})();
